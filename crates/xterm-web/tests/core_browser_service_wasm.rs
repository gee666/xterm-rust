#[wasm_bindgen_test(async)]
async fn focus_cache_and_adopted_owner_document_match_source() {
    let (s, r, sd, rd) = (
        Fixture::new(true),
        Fixture::new(true),
        Fixture::new(true),
        Fixture::new(true),
    );
    sd.0.set_doc_focus(false);
    rd.0.set_doc_focus(false);
    let source = SourceCore::new(&s.0.textarea(), &s.0.window(), &sd.0.document()).unwrap();
    let rust = CoreBrowserService::new(&r.0.textarea(), &r.0.window(), &rd.0.document()).unwrap();
    same_calls(&s.0, &r.0);
    assert!(!source.focused().unwrap());
    assert!(!rust.is_focused().unwrap());
    s.0.focus();
    r.0.focus();
    assert!(!source.focused().unwrap());
    assert!(!rust.is_focused().unwrap());
    checkpoint().await;
    assert!(source.focused().unwrap());
    assert!(rust.is_focused().unwrap());
    s.0.adopt(&sd.0);
    r.0.adopt(&rd.0);
    assert!(source.focused().unwrap());
    assert!(rust.is_focused().unwrap());
    checkpoint().await;
    assert!(!source.focused().unwrap());
    assert!(!rust.is_focused().unwrap());
    s.0.blur();
    r.0.blur();
    checkpoint().await;
    assert!(!source.focused().unwrap());
    assert!(!rust.is_focused().unwrap());
    same_calls(&s.0, &r.0);
    same_calls(&sd.0, &rd.0);
    assert_eq!(rust.main_document(), rd.0.document());
    source.dispose().unwrap();
    rust.dispose().unwrap();
    same_calls(&s.0, &r.0);
}

#[wasm_bindgen_test]
fn raw_dpr_and_legacy_query_rearming_match_source() {
    let (s, r) = (Fixture::new(true), Fixture::new(true));
    let source = SourceCore::new(&s.0.textarea(), &s.0.window(), &s.0.document()).unwrap();
    let rust = CoreBrowserService::new(&r.0.textarea(), &r.0.window(), &r.0.document()).unwrap();
    same_calls(&s.0, &r.0);
    for value in [
        1.0,
        1.25,
        0.0,
        -0.0,
        f64::NAN,
        f64::NAN,
        f64::INFINITY,
        1e-7,
        1e21,
    ] {
        s.0.set_dpr(value);
        r.0.set_dpr(value);
        s.0.resize();
        r.0.resize();
        let (expected, actual) = (source.ratio().unwrap(), rust.dpr().unwrap());
        if expected.is_nan() {
            assert!(actual.is_nan());
        } else {
            assert_eq!(expected.to_bits(), actual.to_bits());
        }
        same_calls(&s.0, &r.0);
        s.0.media();
        r.0.media();
        same_calls(&s.0, &r.0);
    }
    source.dispose().unwrap();
    rust.dispose().unwrap();
    same_calls(&s.0, &r.0);
}

#[wasm_bindgen_test]
fn window_switch_and_same_identity_match_source() {
    let (s, r, sw, rw) = (
        Fixture::new(true),
        Fixture::new(true),
        Fixture::new(true),
        Fixture::new(true),
    );
    sw.0.set_dpr(2.0);
    rw.0.set_dpr(2.0);
    let source = SourceCore::new(&s.0.textarea(), &s.0.window(), &s.0.document()).unwrap();
    let rust = CoreBrowserService::new(&r.0.textarea(), &r.0.window(), &r.0.document()).unwrap();
    source.set_window(&s.0.window()).unwrap();
    rust.set_window(&r.0.window()).unwrap();
    same_calls(&s.0, &r.0);
    source.set_window(&sw.0.window()).unwrap();
    rust.set_window(&rw.0.window()).unwrap();
    same_calls(&s.0, &r.0);
    same_calls(&sw.0, &rw.0);
    assert_eq!(rust.window(), rw.0.window());
    assert_eq!(rust.main_document(), r.0.document());
    source.dispose().unwrap();
    rust.dispose().unwrap();
    same_calls(&sw.0, &rw.0);
}
