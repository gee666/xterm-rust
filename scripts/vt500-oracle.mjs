import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import { createHash } from 'node:crypto';

const sourcePath = 'source_repo/src/common/parser/EscapeSequenceParser.ts';
const constantsPath = 'source_repo/src/common/parser/Constants.ts';
const source = await readFile(sourcePath, 'utf8');
const constants = await readFile(constantsPath, 'utf8');
const normalized = source.replace(/\r\n/g, '\n');
const marker = '\n/**\n * EscapeSequenceParser.';
const end = normalized.indexOf(marker);
assert(end > 0, 'transition definition boundary changed');
// Stop before EscapeSequenceParser itself. Only TransitionTable, constants and
// the complete original VT500 rule initializer execute. No rule is rewritten.
const tableSource = normalized.slice(0, end).replace(/^import .*;\n/gm, '');
const js = stripTypeScriptTypes(constants + '\n' + tableSource, { mode: 'transform' });
const { VT500_TRANSITION_TABLE, TransitionTable, ParserState, ParserAction } = await import(
  `data:text/javascript;base64,${Buffer.from(js).toString('base64')}`
);
const expected = Array.from(VT500_TRANSITION_TABLE.table);
assert.equal(expected.length, 4257);
assert.equal(ParserState.STATE_LENGTH, 17);
for (const value of expected) {
  assert(value >>> 8 <= ParserAction.APC_END);
  assert((value & 255) < ParserState.STATE_LENGTH);
}
// Verify the source custom-table operations as well as immutable default data.
const custom = new TransitionTable(512);
assert(custom.table.every(value => value === 0));
custom.setDefault(ParserAction.ERROR, ParserState.GROUND);
assert(custom.table.every(value => value === 256));
custom.add(65, ParserState.GROUND, ParserAction.PRINT, ParserState.ESCAPE);
assert.equal(custom.table[65], 513);
custom.addMany([1, 2, 3], ParserState.ESCAPE, ParserAction.EXECUTE, ParserState.GROUND);
for (const code of [1, 2, 3]) assert.equal(custom.table[256 + code], 768);

const rustPath = 'crates/xterm-core/src/parser/vt500_table.rs';
const fixturePath = 'crates/xterm-core/tests/fixtures/vt500-table.txt';
if (process.argv.includes('--generate')) {
  const lines = [];
  for (let i = 0; i < expected.length; i += 16) lines.push('    ' + expected.slice(i, i + 16).join(', ') + ',');
  const rust = '// Copyright (c) 2017-2018 The xterm.js authors. All rights reserved.\n'
    + '// Licensed under MIT. Generated by scripts/vt500-oracle.mjs.\n'
    + '// These protocol transitions come from the unmodified upstream initializer.\n'
    + 'pub(super) const VT500: [u16; 4257] = [\n' + lines.join('\n') + '\n];\n';
  await writeFile(rustPath, rust);
  await mkdir('crates/xterm-core/tests/fixtures', { recursive: true });
  await writeFile(fixturePath, expected.join('\n') + '\n');
} else {
  const rust = await readFile(rustPath, 'utf8');
  const array = rust.slice(rust.indexOf('= [') + 3, rust.lastIndexOf(']'));
  const actual = array.split(',').map(value => value.trim()).filter(Boolean).map(Number);
  assert.deepEqual(actual, expected, 'Rust transitions differ from original rules');
  const fixture = (await readFile(fixturePath, 'utf8')).trim().split(/\r?\n/).map(Number);
  assert.deepEqual(fixture, expected, 'test fixture differs from original rules');
}
await mkdir('results/vt500', { recursive: true });
const summary = {
  sourcePath, constantsPath,
  sourceSha256: createHash('sha256').update(source).digest('hex'),
  constantsSha256: createHash('sha256').update(constants).digest('hex'),
  node: process.version, platform: process.platform,
  states: 17, actions: 18, comparedEntries: expected.length,
  customTableAssertions: 6,
  status: process.argv.includes('--generate') ? 'generated' : 'matched'
};
await writeFile('results/vt500/oracle.json', JSON.stringify(summary, null, 2) + '\n');
console.log(JSON.stringify(summary, null, 2));
