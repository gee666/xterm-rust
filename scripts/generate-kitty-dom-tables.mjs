import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = readFileSync(resolve(root, 'source_repo/src/common/input/KittyKeyboard.ts'), 'utf8').replaceAll('\r\n', '\n');
const bodies = ['_functionalKeyCodes', '_csiTildeKeys', '_csiLetterKeys', '_ss3FunctionKeys'].map(name => {
  const body = source.match(new RegExp(name + '[^=]*= \\{([\\s\\S]*?)\\n  \\};'))?.[1];
  assert.ok(body, 'missing source table ' + name);
  return body.trimEnd();
});
const output = '// Copyright (c) 2025 The xterm.js authors. All rights reserved.\n' +
  '// Licensed under MIT. Generated by scripts/generate-kitty-dom-tables.mjs.\n' +
  '// Intentional binding-data copy: ordinary literals preserve property order,\n' +
  '// bypass inherited setters and use the executing realm\'s prototype.\n' +
  'export function kittyCreateTables() {\n  return [\n' +
  bodies.map(body => '    {' + body + '\n    }').join(',\n') + '\n  ];\n}\n\n' +
  '// String addition uses the default hint and rejects Symbols.\n' +
  'export function keyboardDefaultText(value) { return \'\' + value; }\n';
const file = resolve(root, 'crates/xterm-web/src/input/kitty_tables.js');
if (process.argv.includes('--write')) writeFileSync(file, output);
else assert.equal(readFileSync(file, 'utf8'), output, 'Kitty binding data is stale. Run with --write.');
console.log('Kitty literal binding tables match all four source objects.');
