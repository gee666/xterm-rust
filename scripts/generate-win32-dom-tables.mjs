import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = readFileSync(resolve(root, 'source_repo/src/common/input/Win32InputMode.ts'), 'utf8').replaceAll('\r\n', '\n');
const bodies = ['_codeToVk', '_codeToScancode', '_keyToControlChar'].map(name => {
  const body = source.match(new RegExp(name + '[^=]*= \\{([\\s\\S]*?)\\n  \\};'))?.[1];
  assert.ok(body, 'missing source table ' + name);
  return body.trimEnd();
});
const output = '// Copyright (c) 2026 The xterm.js authors. All rights reserved.\n' +
  '// Licensed under MIT. Generated by scripts/generate-win32-dom-tables.mjs.\n' +
  '// Intentional binding-data copy: literals preserve source property order,\n' +
  '// bypass inherited setters, and have the executing JS realm\'s prototype.\n' +
  'export function win32CreateTables() {\n  return [\n' +
  bodies.map(body => '    {' + body + '\n    }').join(',\n') + '\n  ];\n}\n\n' +
  '// Template interpolation differs from String(value) for Symbols. Keep the\n' +
  '// exact language operation and throw value instead of normalizing errors.\n' +
  'export function win32TemplateText(value) { return `\${value}`; }\n';
const path = resolve(root, 'crates/xterm-web/src/input/win32_tables.js');
if (process.argv.includes('--write')) writeFileSync(path, output);
else assert.equal(readFileSync(path, 'utf8'), output, 'Win32 binding data is stale. Run with --write.');
console.log('Win32 literal binding tables match all three source objects.');
