for (const code of allCodes) {
  for (let flags = 0; flags < 16; flags++) {
    for (const down of [false, true]) {
      const event = { code, key: keys[random() % keys.length], keyCode: random() % 256,
        altKey: !!(flags & 1), ctrlKey: !!(flags & 2), shiftKey: !!(flags & 4), metaKey: !!(flags & 8) };
      cases.push({ event, down, result: context.encoder.evaluateKeyboardEvent(event, down), name: `mapped ${code}` });
    }
  }
}
for (let i = 0; i < 10000; i++) {
  const flags = random() & 15;
  const event = { code: allCodes[random() % allCodes.length], key: String.fromCharCode(random() & 0xffff),
    keyCode: random(), altKey: !!(flags & 1), ctrlKey: !!(flags & 2), shiftKey: !!(flags & 4), metaKey: !!(flags & 8) };
  const down = !!(random() & 1);
  cases.push({ event, down, result: context.encoder.evaluateKeyboardEvent(event, down), name: `random ${i}` });
}

