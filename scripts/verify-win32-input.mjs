const tablePath = path.join(root, 'crates/xterm-core/src/input/win32_key_codes.rs');
function table(name) {
  const body = source.match(new RegExp(`${name}[^=]*= \\{([\\s\\S]*?)\\n  \\};`))?.[1];
  assert.ok(body, `missing ${name}`);
  return [...body.matchAll(/'([^']+)':\s*(0x[0-9A-Fa-f]+)/g)].map(m => [m[1], m[2].toLowerCase()]);
}
const vk = table('_codeToVk');
