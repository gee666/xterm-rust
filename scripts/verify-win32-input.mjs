// Cover every lookup plus reproducible malformed/non-BMP UTF-16 and modifier combinations.
const allCodes = [...new Set([...vk.map(x => x[0]), ...scan.map(x => x[0]), 'Unknown', ''])];
const keys = ['a', 'A', 'z', 'é', '中', '😀', '\ud800', '\udfff', '', 'Enter', 'Backspace', 'Tab', 'Escape', 'ArrowUp', ' ', '/', '\0'];
const seed = 0x573332;
let state = seed;
function random() { state = (Math.imul(state, 1664525) + 1013904223) >>> 0; return state; }
