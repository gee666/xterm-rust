import {readFile,writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import path from 'node:path';
import vm from 'node:vm';
const sourceRoot=path.resolve(process.env.SOURCE_ROOT??'source_repo');
const require=createRequire(path.resolve(process.env.REFERENCE_ROOT??sourceRoot,'package.json'));
const {build}=require('esbuild');
const input=path.join(sourceRoot,'addons/addon-webgl/src/customGlyphs/CustomGlyphDefinitions.ts');
const built=await build({entryPoints:[input],bundle:true,write:false,format:'cjs',platform:'node'});
const module={exports:{}};
vm.runInNewContext(built.outputFiles[0].text,{module,exports:module.exports});
const {customGlyphDefinitions:definitions,blockPatternCodepoints}=module.exports;
const q=JSON.stringify;
const n=value=>Number.isInteger(value)?value+'.0':String(value);
function dynamic(fn) {
  const a=fn(.15,.075),b=fn(.15,.45),c=fn(0,0);
  if(a===b&&b===c)return `Path::Static(${q(a)})`;
  const template=fn.toString().match(/=>\s*`([\s\S]*)`$/)?.[1];
  if(!template)throw new Error('Unsupported generated function: '+fn);
  const expressions=[];
  const format=template.replace(/\$\{([^}]+)\}/g,(_,expression)=>{
    expression=expression.replace(/\/\*[\s\S]*?\*\//g,'').trim();
    if(expression.startsWith('"'))return JSON.parse(expression);
    if(/[^\d.\s+*/()xyp-]/.test(expression))throw new Error('Unsupported path expression '+expression);
    expressions.push(expression.replace(/(?:\d+\.\d*|\.\d+|\d+)/g,number=>n(Number(number))));
    return '{}';
  });
  return `Path::Dynamic(|xp, yp| { let _ = (xp, yp); format!(${q(format)}, ${expressions.join(', ')}) })`;
}
const patternIds=new Map();
function part(p) {
  let data;
  switch(p.type) {
    case 0:data=`Definition::Blocks(&[${p.data.map(v=>`Octant { x: ${n(v.x)}, y: ${n(v.y)}, w: ${n(v.w)}, h: ${n(v.h)} }`).join(',')}])`;break;
    case 1:
      if(!patternIds.has(p.data))patternIds.set(p.data,patternIds.size);
      data=`Definition::Pattern(${patternIds.get(p.data)}, &[${p.data.map(row=>'&['+row.join(',')+']').join(',')}])`;break;
    case 2:data=`Definition::PathFunction(${typeof p.data==='function'?dynamic(p.data):`Path::Static(${q(p.data)})`})`;break;
    case 3:data=`Definition::Path(${q(p.data)})`;break;
    case 4:case 5:data=`Definition::${p.type===4?'Negative':'Vector'}(Vector { path: ${q(p.data.d)}, stroke: ${p.data.type===1}, left: ${n(p.data.leftPadding??0)}, right: ${n(p.data.rightPadding??0)} })`;break;
    case 6:data=`Definition::Braille(${p.data})`;break;
    default:throw new Error('Unknown definition type '+p.type);
  }
  return `Part { data: ${data}, scale_char: ${p.scaleType===1}, clip: ${p.clipPath?'Some('+q(p.clipPath)+')':'None'}, stroke: ${p.strokeWidth===undefined?'None':'Some('+n(p.strokeWidth)+')'} }`;
}
const lines=[
'// Copyright (c) 2021 The xterm.js authors. All rights reserved. MIT license.',
'// Generated by scripts/custom-glyph-definitions.mjs from unchanged source definitions.',
'// Cohesive Unicode glyph data exceeds the 350-line limit. Do not edit by hand.',
'// Source SHA-256 '+createHash('sha256').update(await readFile(input)).digest('hex'),
'use super::types::{Definition, Octant, Part, Path, Vector};',
'pub(super) fn lookup(codepoint: u32) -> Option<&\'static [Part]> {',
'    Some(match codepoint {'
];
for(const [c,parts]of Object.entries(definitions))lines.push(`        0x${c.codePointAt(0).toString(16)} => &[${(Array.isArray(parts)?parts:[parts]).map(part).join(', ')}],`);
lines.push('        _ => return None,','    })','}',
'pub(super) fn is_pattern(codepoint: u32) -> bool {',`    matches!(codepoint, ${[...blockPatternCodepoints].map(n=>'0x'+n.toString(16)).join(' | ')})`,'}');
await writeFile('crates/xterm-web/src/webgl/custom_glyphs/definitions.rs',lines.join('\n')+'\n');
console.log(Object.keys(definitions).length+' custom glyph definitions generated');
