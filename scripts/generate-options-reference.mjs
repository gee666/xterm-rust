// Generate a test-only module from the unchanged reference, never production glue.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { createHash } from 'node:crypto';
const files = ['common/Lifecycle.ts', 'common/Event.ts', 'common/services/OptionsService.ts'];
const hashes = {};
const code = files.map(file => {
  const source = readFileSync(`source_repo/src/${file}`, 'utf8');
  hashes[file] = createHash('sha256').update(source).digest('hex');
  return `// Reference ${file}\n` + stripTypeScriptTypes(source.replace(/^import .*;\r?$/gm, '').replace(/\bexport /g, ''), {mode:'transform'});
}).join('\n');
mkdirSync('crates/xterm-wasm-support/tests/reference', {recursive:true});
writeFileSync('crates/xterm-wasm-support/tests/reference/options-reference.js',
  '// Copyright (c) 2019-2026 The xterm.js authors. MIT license.\n' +
  '// Generated unchanged reference fixture. Cohesive upstream source exceeds350lines.\n' +
  '// Generated by scripts/generate-options-reference.mjs. Test use only.\n' +
  'const isMac = false;\n' + code + '\nexport function referenceOptions(input) { return new OptionsService(input); }\n' +
  `export function referencePublic(service) {
    const core = service.options;
    const view = {...core};
    const getter = key => core[key];
    const setter = (key,value) => {
      if (key==='cols'||key==='rows') throw new Error('Option "'+key+'" can only be set in the constructor');
      core[key]=value;
    };
    for (const key in core) Object.defineProperty(view,key,{get:getter.bind(null,key),set:setter.bind(null,key)});
    return view;
  }\n`);
mkdirSync('results/options', {recursive:true});
writeFileSync('results/options/browser-reference.json', JSON.stringify({
  generator:'node scripts/generate-options-reference.mjs', node:process.version,
  scope:'Original OptionsService only. referencePublic faithfully transcribes the public option-descriptor loop, not a full original Terminal engine.', sourceSha256:hashes,
  generatedSha256:createHash('sha256').update(readFileSync('crates/xterm-wasm-support/tests/reference/options-reference.js')).digest('hex')
},null,2)+'\n');
