// Keep the test-only oracle equal to the unchanged reference class. The Rust
// library never imports this fixture or delegates scroll decisions to it.
import {createRequire} from 'node:module';
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';

const root=resolve(import.meta.dirname,'..');
const require=createRequire(import.meta.url);
const esbuild=require(process.env.ESBUILD_MODULE??resolve(root,'source_repo/node_modules/esbuild'));
const source=await readFile(resolve(root,'source_repo/src/browser/scrollable/scrollable.ts'),'utf8');
const start=source.indexOf('export class ScrollState ');
const end=source.indexOf('export interface IScrollDimensions ',start);
if(start<0||end<0)throw new Error('Reference ScrollState class boundaries changed');
const compiled=esbuild.transformSync(source.slice(start,end),{loader:'ts',format:'esm',target:'es2022'}).code;
const hash=createHash('sha256').update(source).digest('hex');
const cases=await readFile(resolve(root,'crates/xterm-web/tests/raw_scroll_state_cases.js'),'utf8');
const fixture=`// Copyright (c) Microsoft Corporation. All rights reserved. MIT license.\n// Generated by scripts/raw-scroll-state-source.mjs from unchanged ScrollState.\n// Complete scrollable.ts SHA-256: ${hash}\n${compiled}\n${cases}`;
const output=resolve(root,'crates/xterm-web/tests/raw_scroll_state_oracle.js');
const args=process.argv.slice(2);
if(args.length===1&&args[0]==='--write')await writeFile(output,fixture);
else {
  if(args.length)throw new Error('Usage: node scripts/raw-scroll-state-source.mjs [--write]');
  if(await readFile(output,'utf8')!==fixture)throw new Error('Raw ScrollState oracle differs from source; inspect before regenerating');
}
console.log(`ScrollState oracle matches unchanged source ${hash}`);
