// Exact control-string declaration inventory. No compiler or bundler is invoked.
import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const sourcePath = 'source_repo/src/common/data/EscapeSequences.ts';
const rustPath = 'crates/xterm-core/src/data/escape_sequences.rs';
const source = await readFile(sourcePath, 'utf8');
const modules = { C0: 'c0', C1: 'c1', C1ESCAPED: 'c1_escaped' };
function decode(literal) {
  // These source strings contain only shared JS/Rust escapes and BMP controls.
  // Reject unfamiliar literals rather than executing source with eval.
  let body = literal.slice(1, -1).replace(/\\x([0-9a-f]{2})/gi, (_, hex) => '\\u00' + hex);
  body = body.replace(/\\u\{([0-9a-f]{1,4})\}/gi, (_, hex) => '\\u' + hex.padStart(4, '0'));
  return JSON.parse('"' + body + '"');
}
const groups = [];
for (const match of source.matchAll(/export const enum (C0|C1|C1ESCAPED)\s*\{([\s\S]*?)\r?\n\}/g)) {
  const entries = [];
  for (const entry of match[2].matchAll(/(?:\/\*\*\s*(.*?)\s*\*\/\s*)?([A-Z0-9_]+)\s*=\s*('(?:\\.|[^'])*')/g)) {
    entries.push({ name: entry[2], value: decode(entry[3]), comment: entry[1] ?? '7-bit string terminator.' });
  }
  groups.push({ source: match[1], module: modules[match[1]], entries });
}
assert.deepEqual(groups.map(group => [group.source, group.entries.length]), [['C0', 34], ['C1', 32], ['C1ESCAPED', 1]]);
function literal(value) {
  let result = '"';
  for (const char of value) {
    const code = char.codePointAt(0);
    if (char === '\\' || char === '"') result += '\\' + char;
    else if (code >= 0x20 && code < 0x7f) result += char;
    else if (code <= 0x7f) result += `\\x${code.toString(16).padStart(2, '0')}`;
    else result += `\\u{${code.toString(16).padStart(4, '0')}}`;
  }
  return result + '"';
}
if (process.argv.includes('--generate')) {
  const lines = ['// Copyright (c) 2017 The xterm.js authors. All rights reserved.',
    '// Licensed under MIT. Generated by scripts/escape-sequences-oracle.mjs.',
    '// Reference: common/data/EscapeSequences.ts.',
    '//! Named control strings preserve the original UTF-16 values.',
    '//! C1 strings encode as two UTF-8 bytes; they are not raw single-byte input.', ''];
  for (const group of groups) {
    lines.push(`/// ${group.source} control strings from xterm.js.`, `pub mod ${group.module} {`);
    for (const entry of group.entries) lines.push(`    /// ${entry.comment}`, `    pub const ${entry.name}: &str = ${literal(entry.value)};`);
    lines.push('}', '');
  }
  await mkdir('crates/xterm-core/src/data', { recursive: true });
  await writeFile(rustPath, lines.join('\n'));
} else {
  const rust = await readFile(rustPath, 'utf8');
  for (const group of groups) {
    const block = rust.match(new RegExp(`pub mod ${group.module}\\s*\\{([\\s\\S]*?)\\r?\\n\\}`));
    assert(block, `missing module ${group.module}`);
    const actual = Array.from(block[1].matchAll(/pub const ([A-Z0-9_]+): &str = ("(?:\\.|[^"])*");/g), entry => [entry[1], decode(entry[2])]);
    assert.deepEqual(actual, group.entries.map(entry => [entry.name, entry.value]), `${group.source} names or values drifted`);
  }
}
const report = { sourcePath, sourceSha256: createHash('sha256').update(source).digest('hex'), rustPath,
  rustSha256: createHash('sha256').update(await readFile(rustPath)).digest('hex'),
  node: process.version, platform: process.platform, groups: groups.map(group => ({ name: group.source, declarations: group.entries.length })),
  declarationsCompared: groups.reduce((count, group) => count + group.entries.length, 0),
  units: groups.flatMap(group => group.entries.map(entry => ({ name: `${group.source}.${entry.name}`,
    utf16: Array.from({ length: entry.value.length }, (_, index) => entry.value.charCodeAt(index)), utf8Bytes: Buffer.byteLength(entry.value) }))),
  originalDedicatedSuiteClaimed: 0, status: process.argv.includes('--generate') ? 'generated' : 'matched' };
await mkdir('results/escape-sequences', { recursive: true });
await writeFile('results/escape-sequences/source.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ declarations: report.declarationsCompared, groups: report.groups, status: report.status }));
