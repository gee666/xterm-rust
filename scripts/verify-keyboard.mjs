import os from 'node:os';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = name => readFileSync(path.join(root, name), 'utf8');
const sourcePath = 'source_repo/src/common/input/Keyboard.ts';
const testPath = sourcePath.replace('.ts', '.test.ts');
const outputDir = path.join(root, 'results/keyboard');
const tmp = path.join(root, 'tmp/keyboard');
mkdirSync(outputDir, { recursive: true });
mkdirSync(tmp, { recursive: true });
function erase(source) {
  return stripTypeScriptTypes(source.replace(/^import .*;\r?$/gm, '').replace(/^export /gm, ''), { mode: 'transform' });
}
const suite = [];
const names = [];
const captured = [];
let activeName = '';
let assertions = 0;
const context = vm.createContext({
  assert: {
    equal: (actual, expected) => { assertions++; assert.equal(actual, expected); },
    strictEqual: (actual, expected) => { assertions++; assert.strictEqual(actual, expected); }
  },
  describe: (name, run) => { names.push(name); run(); names.pop(); },
  it: (name, run) => suite.push({ name: [...names, name].join(' / '), run })
});
const typeEnum = read('source_repo/src/common/Types.ts').match(/export const enum KeyboardResultType\s*\{[^}]*\}/)?.[0];
assert.ok(typeEnum, 'upstream KeyboardResultType not found');
vm.runInContext(erase(read('source_repo/src/common/data/EscapeSequences.ts')) + '\n' + erase(typeEnum) + '\n' + erase(read(sourcePath)), context);
const upstreamEvaluate = context.evaluateKeyboardEvent;
context.evaluateKeyboardEvent = (event, ...options) => {
  const result = upstreamEvaluate(event, ...options);
  if (activeName) captured.push({ name: activeName, event, options, result });
  return result;
};
vm.runInContext(erase(read(testPath)), context);
for (const test of suite) {
  activeName = test.name;
  test.run();
}
activeName = '';
assert.equal(assertions, captured.length, 'every assertion must have a captured event');
const hex = text => Array.from({ length: text.length }, (_, i) => text.charCodeAt(i).toString(16)).join(',');
function resultRow(result) {
  return `${result.type}\t${Number(result.cancel)}\t${result.key === undefined ? '-' : hex(result.key)}`;
}
function eventRow(item) {
  const { event: e, options: o } = item;
  const modifiers = Number(e.shiftKey) | Number(e.altKey) << 1 | Number(e.ctrlKey) << 2 | Number(e.metaKey) << 3;
  const options = Number(o[0]) | Number(o[1]) << 1 | Number(o[2]) << 2;
  return [e.keyCode, hex(e.key), hex(e.code), modifiers, options].join('\t');
}
const fixture = captured.map(item => `${eventRow(item)}\t${resultRow(item.result)}\t${item.name}`).join('\n') + '\n';
const fixturePath = path.join(root, 'crates/xterm-core/tests/fixtures/keyboard_upstream.tsv');
if (process.argv.includes('--generate')) {
  mkdirSync(path.dirname(fixturePath), { recursive: true });
  writeFileSync(fixturePath, fixture);
} else {
  assert.equal(readFileSync(fixturePath, 'utf8'), fixture, 'upstream fixture drift; review before --generate');
}

// Pin the reference engine's Unicode data instead of inheriting rustc's version.
assert.equal(process.versions.unicode, '17.0', 'keyboard lowercase data requires a Unicode 17 JS oracle');
const lowerPairs = [];
for (let unit = 0; unit < 65536; unit++) {
  const lower = String.fromCharCode(unit).toLowerCase();
  if (unit === 0x130) { assert.equal(hex(lower), '69,307'); continue; }
  assert.equal(lower.length, 1, `unexpected multi-unit lowercase U+${unit.toString(16)}`);
  if (lower.charCodeAt(0) !== unit) lowerPairs.push(`(0x${unit.toString(16)}, 0x${lower.charCodeAt(0).toString(16)})`);
}
let lowerSource = '// Generated by scripts/verify-keyboard.mjs --generate from Unicode 17.0 JS lowercase.\n';
lowerSource += '// Unicode data license: licenses/UNICODE-3.0.txt. Do not edit by hand.\n';
lowerSource += '// Explicit data keeps JS behavior independent of the Rust compiler Unicode version.\n// This cohesive generated BMP lookup table exceeds 350 lines to retain every mapping.\n\n';
lowerSource += 'pub(crate) fn lowercase_first(unit: u16) -> u16 {\n';
lowerSource += '    if unit == 0x130 { 0x69 } else {\n';
lowerSource += '        MAPPINGS.binary_search_by_key(&unit, |pair| pair.0)\n';
lowerSource += '            .map(|index| MAPPINGS[index].1).unwrap_or(unit)\n    }\n}\n\n';
lowerSource += 'pub(crate) fn append_lowercase(output: &mut Vec<u16>, unit: u16) {\n';
lowerSource += '    output.push(lowercase_first(unit));\n    if unit == 0x130 { output.push(0x307); }\n}\n\n';
lowerSource += 'const MAPPINGS: &[(u16, u16)] = &[\n';
for (let i = 0; i < lowerPairs.length; i += 4) lowerSource += `    ${lowerPairs.slice(i, i + 4).join(', ')},\n`;
lowerSource += '];\n';
// rustfmt formats generated rows consistently; compare normalized files afterward.
const lowerPath = path.join(root, 'crates/xterm-core/src/input/keyboard_lowercase.rs');
if (process.argv.includes('--generate')) {
  writeFileSync(lowerPath, lowerSource);
  const formatted = spawnSync(process.env.RUSTFMT || 'rustfmt', ['--edition', '2021', lowerPath], { encoding: 'utf8', timeout: 120000 });
  if (formatted.error) throw formatted.error;
  assert.equal(formatted.status, 0, formatted.stderr);
} else {
  // Verify mappings rather than formatter whitespace to permit newer rustfmt.
  const actual = readFileSync(lowerPath, 'utf8').match(/const MAPPINGS[^=]*= \[?&?\[([\s\S]*?)\];/)?.[1];
  assert.ok(actual, 'generated lowercase table missing');
  assert.deepEqual([...actual.matchAll(/\(0x([0-9a-f]+),\s*0x([0-9a-f]+)\)/g)].map(m => `(0x${m[1]}, 0x${m[2]})`), lowerPairs);
}

const seed = 0x4b455953;
let state = seed;
function random() {
  state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
  return state;
}
const cases = [...captured];
function add(keyCode, key, code, modifiers, flags, name) {
  const event = { keyCode, key, code, shiftKey: !!(modifiers & 1), altKey: !!(modifiers & 2),
    ctrlKey: !!(modifiers & 4), metaKey: !!(modifiers & 8) };
  const options = [!!(flags & 1), !!(flags & 2), !!(flags & 4)];
  cases.push({ name, event, options, result: upstreamEvaluate(event, ...options) });
}
const keys = ['', 'a', 'A', 'c', '/', '@', '^', '_', 'é', '中', '😀', '\ud800', '\udfff', 'Enter', 'Dead', '\0'];
const codes = ['', 'KeyN', 'KeyE', 'KeyU', 'Minus', 'Digit2', 'Digit6', 'Key', 'Keyİ', 'Key😀', 'Key\ud800'];
for (let keyCode = 0; keyCode < 256; keyCode++) {
  for (let modifiers = 0; modifiers < 16; modifiers++) {
    for (let flags = 0; flags < 8; flags++) {
      add(keyCode, keys[random() % keys.length], codes[random() % codes.length], modifiers, flags, 'keycode/modifier/options matrix');
    }
  }
}
for (const mobile of ['UIKeyInputUpArrow', 'UIKeyInputDownArrow', 'UIKeyInputLeftArrow', 'UIKeyInputRightArrow']) {
  for (let modifiers = 0; modifiers < 16; modifiers++) {
    for (let flags = 0; flags < 8; flags++) add(0, mobile, '', modifiers, flags, 'mobile arrows');
  }
}
// Exhaust JS single-code-unit behavior and Dead-key slice/lowercase semantics.
for (let unit = 0; unit < 65536; unit++) {
  const key = String.fromCharCode(unit);
  add(65, key, '', 0, 0, 'single UTF-16 key');
  add(255, 'Dead', `Key${key}`, 2, 0, 'Dead lowercase BMP unit');
  add(255, 'Dead', `Key${key}`, 3, 0, 'Dead shifted BMP unit');
}
for (const code of codes) {
  for (let modifiers = 0; modifiers < 16; modifiers++) {
    for (let flags = 0; flags < 8; flags++) add(255, 'Dead', code, modifiers, flags, 'Dead-code options');
  }
}
for (let i = 0; i < 20000; i++) {
  // Use high bits for flags: low LCG bits repeat too often for independent fields.
  const modifiers = random() >>> 28;
  const flags = random() >>> 29;
  const keyCode = i % 2 ? random() : random() >>> 24;
  const key = i % 3 ? keys[random() % keys.length] : String.fromCharCode(random() & 0xffff, random() & 0xffff);
  add(keyCode, key, codes[random() % codes.length], modifiers, flags, 'seeded malformed keys');
}
const runner = `#[path = ${JSON.stringify(path.join(root, 'crates/xterm-core/src/input/keyboard.rs').replaceAll('\\', '/'))}]
mod keyboard;
use std::io::{self, BufRead};
fn units(s: &str) -> Vec<u16> {
    s.split(',').filter(|s| !s.is_empty()).map(|s| u16::from_str_radix(s, 16).expect("generated UTF-16")).collect()
}
fn main() {
    for line in io::stdin().lock().lines() {
        let line = line.expect("stdin read");
        let p: Vec<_> = line.split('\\t').collect();
        let key = units(p[1]); let code = units(p[2]);
        let m: u8 = p[3].parse().expect("modifiers"); let o: u8 = p[4].parse().expect("options");
        let e = keyboard::KeyboardEvent { key_code: p[0].parse().expect("keyCode"), key: &key, code: &code,
            shift_key: m & 1 != 0, alt_key: m & 2 != 0, ctrl_key: m & 4 != 0, meta_key: m & 8 != 0 };
        let r = keyboard::evaluate_keyboard_event(&e, o & 1 != 0, o & 2 != 0, o & 4 != 0);
        let output = r.key.map(|key| key.iter().map(|unit| format!("{unit:x}")).collect::<Vec<_>>().join(",")).unwrap_or_else(|| "-".into());
        println!("{}\\t{}\\t{}", r.result_type as u8, u8::from(r.cancel), output);
    }
}`;
const runnerPath = path.join(tmp, 'runner.rs');
const binary = path.join(tmp, process.platform === 'win32' ? 'runner.exe' : 'runner');
writeFileSync(runnerPath, runner);
function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', timeout: 120000, maxBuffer: 64 * 1024 * 1024, ...options });
  if (result.error) throw result.error;
  assert.equal(result.status, 0, `${command} ${args.join(' ')}\n${result.stderr}\n${result.stdout}`);
  return result;
}
const rustc = process.env.RUSTC || 'rustc';
run(rustc, ['--edition=2021', '-Dwarnings', runnerPath, '-o', binary]);
const actual = run(binary, [], { input: cases.map(eventRow).join('\n') + '\n' }).stdout.trimEnd().split(/\r?\n/);
assert.equal(actual.length, cases.length);
for (let i = 0; i < cases.length; i++) {
  const expected = resultRow(cases[i].result);
  if (actual[i] !== expected) {
    writeFileSync(path.join(outputDir, 'counterexample.json'), JSON.stringify({ seed, index: i, case: cases[i], actual: actual[i], expected }, null, 2));
    assert.equal(actual[i], expected, `case ${i} ${cases[i].name}`);
  }
}
const sha256 = name => createHash('sha256').update(readFileSync(path.join(root, name))).digest('hex');
const report = { command: 'node scripts/verify-keyboard.mjs', platform: process.platform, arch: process.arch,
  osRelease: os.release(), cpu: os.cpus()[0]?.model,
  sourceHashes: { [sourcePath]: sha256(sourcePath), [testPath]: sha256(testPath) },
  node: process.version, unicode: process.versions.unicode, rustc: run(rustc, ['--version']).stdout.trim(), seed,
  upstream: { discovered: suite.length, executed: suite.length, passed: suite.length, failed: 0, skipped: 0, unrun: 0,
    assertions, migratedAssertions: captured.length, names: suite.map(t => t.name) },
  differential: { executed: cases.length, passed: cases.length, failed: 0,
    keycodeModifierOptionMatrix: 256 * 16 * 8, bmpCases: 65536 * 3, randomCases: 20000 },
  scope: 'Legacy Keyboard.ts policy only. Browser integration and full terminal equivalence NOT PROVEN.' };
writeFileSync(path.join(outputDir, 'verification.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ upstreamTests: suite.length, assertions, differential: cases.length, seed }));
