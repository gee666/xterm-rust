test('inventory includes generated sources and configuration but excludes output and dependencies', () => fixture((dir, put) => {
  put('crates/core/src/lib.rs', '// comment\nfn f() {}\n');
  put('crates/core/src/table.rs', '// Generated by test\nconst A: u8 = 1;\n');
  put('crates/core/tests/fixture.tsv', '1\t2\n');
  put('crates/core/Cargo.toml', '[package]\n');
  put('Cargo.lock', 'ignored lock\n');
  for (const path of ['target/generated.rs', 'source_repo/src/a.ts', '.pi/private.rs', 'node_modules/a.js', 'tmp/a.rs', 'docs/data.json', 'results/a.json', 'out-esbuild-test/generated.js']) put(path, 'ignored\n');
  const result = inventory(dir, 'port', rules);
  assert.deepEqual(result.totals, { files: 4, physical: 6, nonblank: 6, bytes: 73 });
  assert.equal(result.byCategory['generated-code-data'].files, 1);
  assert.equal(result.byCategory['test-data'].files, 1);
  assert.equal(result.byCategory.configuration.files, 1);
  assert.equal(result.files.find(row => row.path === 'Cargo.lock').counted, false);
  assert.equal(result.excluded.length, 8);
  assert.deepEqual(result, inventory(dir, 'port', rules));
  for (const groups of [result.byCategory, result.byPurpose, result.byExtension]) {
    const sum = Object.values(groups).reduce((sum, row) => {
      for (const key of Object.keys(sum)) sum[key] += row[key];
      return sum;
    }, { files: 0, physical: 0, nonblank: 0, bytes: 0 });
    assert.deepEqual(sum, result.totals);
  }
}));

test('structured fixture data takes precedence over configuration and lockfile names', () => fixture((dir, put) => {
  put('crates/core/tests/fixtures/trace.json', '[1,2]\n');
  put('crates/core/tests/fixtures/package-lock.json', '{}\n');
  put('crates/core/tests/tsconfig.json', '{}\n');
  put('crates/core/Cargo.toml', '[package]\n');
  const result = inventory(dir, 'port', rules);
  assert.equal(result.totals.files, 4);
  assert.equal(result.byCategory['test-data'].files, 2);
  assert.equal(result.byCategory.configuration.files, 2);
  assert.equal(result.byPurpose.tests.files, 3);
  assert.equal(result.files.find(row => row.path.endsWith('fixtures/package-lock.json')).counted, true);
}));

test('mandatory browser generated glue is counted separately from demo and binary assets', () => fixture((dir, put) => {
  put('browser/pkg/xterm_web.js', 'export function init() {}\n');
  put('browser/pkg/xterm_web_bg.wasm', Buffer.from([0, 97, 115, 109]));
  put('browser/xterm.mjs', "export * from './pkg/xterm_web.js';\n");
  put('browser/xterm.css', '.xterm {}\n');
  put('browser/demo/app.mjs', 'console.log(1);\n');
  const result = inventory(dir, 'port', rules);
  assert.equal(result.totals.files, 4);
  assert.equal(result.byCategory['generated-code-data'].files, 1);
  assert.equal(result.byCategory['bindings-glue'].files, 1);
  assert.equal(result.byCategory['production-library'].files, 1);
  assert.equal(result.byCategory.demos.files, 1);
  assert.equal(result.byPurpose['bindings-glue'].files, 2);
  assert.equal(result.files.find(row => row.path.endsWith('.wasm')).counted, false);
}));

test('UTF-8 BOM bytes do not erase a physical source line', () => fixture((dir, put) => {
  put('src/bom-only.rs', Buffer.from([0xef, 0xbb, 0xbf]));
  put('src/bom-newline.rs', Buffer.from([0xef, 0xbb, 0xbf, 0x0a]));
  const result = inventory(dir, 'source', rules);
  assert.deepEqual(result.totals, { files: 2, physical: 2, nonblank: 0, bytes: 7 });
}));

test('unknown production extensions cannot silently pass classification review', () => fixture((dir, put) => {
  put('crates/core/src/unknown.xyz', 'new language\n');
  const result = inventory(dir, 'port', rules);
  assert.deepEqual(result.unknownProduction, ['crates/core/src/unknown.xyz']);
}));

test('invalid UTF-8 source fails but binary fixtures are listed as assets', () => fixture((dir, put) => {
  put('src/a.rs', Buffer.from([0xff]));
  assert.throws(() => inventory(dir, 'source', rules), /Invalid UTF-8 source/);
  rmSync(resolve(dir, 'src/a.rs'));
  put('test/fixtures/binary.in', Buffer.from([0xff]));
  const result = inventory(dir, 'source', rules);
  assert.equal(result.totals.files, 0);
  assert.equal(result.files[0].counted, false);
  assert.equal(result.files[0].bytes, 1);
}));

test('mixed source/data files are reported without pretending all lines are generated data', () => fixture((dir, put) => {
  put('src/common/input/UnicodeV6.ts', 'const table = [1];\nfunction width() {}\n');
  const result = inventory(dir, 'source', rules);
  assert.equal(result.byCategory['mixed-code-data'].physical, 2);
  assert.equal(result.files[0].generated, false);
  assert.equal(result.files[0].mixedSourceData, true);
}));

test('symlinks require review instead of following outside the tree', () => fixture((dir, put) => {
  put('real/a.rs', 'fn f() {}\n');
  // Windows directory junctions need no symlink privilege and exercise the same guard.
  symlinkSync(resolve(dir, 'real'), resolve(dir, 'linked'), process.platform === 'win32' ? 'junction' : 'dir');
  assert.throws(() => inventory(dir, 'source', rules), /Symlink requires explicit inventory review/);
}));

test('production text data is counted and generator strings are not generated-file markers', () => fixture((dir, put) => {
  put('crates/core/src/table.txt', '1\n2\n');
  put('scripts/generator.mjs', "const header = '// Generated by tool';\n");
  const result = inventory(dir, 'port', rules);
  assert.equal(result.byCategory['generated-code-data'].physical, 2);
  assert.equal(result.byCategory.tooling.files, 1);
}));

test('CLI custom roots exclude their own output and reject baseline mismatches', () => fixture((dir, put) => {
  put('original/src/a.ts', 'export const x = 1;\n');
  put('src/a.rs', 'fn main() {}\n');
  put('reports/old.json', '{}\n');
  const args = [resolve(root, 'scripts/count-loc.mjs'), '--source', resolve(dir, 'original'),
    '--port', dir, '--output', resolve(dir, 'reports')];
  const first = spawnSync(process.execPath, args, { encoding: 'utf8', timeout: 10000 });
  assert.equal(first.status, 0, first.stderr);
  const report = JSON.parse(readFileSync(resolve(dir, 'reports/port.json')));
  assert.equal(report.totals.files, 1);
  const second = spawnSync(process.execPath, args, { encoding: 'utf8', timeout: 10000 });
  assert.equal(second.status, 0, second.stderr);
  assert.equal(JSON.parse(readFileSync(resolve(dir, 'reports/port.json'))).inventorySha256, report.inventorySha256);
  const mismatch = spawnSync(process.execPath, [...args, '--check-baseline'], { encoding: 'utf8', timeout: 10000 });
  assert.notEqual(mismatch.status, 0);
  assert.match(mismatch.stderr, /Pre-launch baseline totals differ/);
}));

