import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync, symlinkSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import test from 'node:test';
import { inventory, lineCounts, purpose, main } from './count-loc.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rules = JSON.parse(readFileSync(resolve(root, 'scripts/loc-rules.json'), 'utf8'));
mkdirSync(resolve(root, 'tmp'), { recursive: true });

function fixture(fn) {
  const dir = mkdtempSync(resolve(root, 'tmp/loc-test-'));
  function put(path, data) {
    const file = resolve(dir, path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, data);
  }
  try { return fn(dir, put); } finally { rmSync(dir, { recursive: true, force: true }); }
}

test('physical lines count final unterminated lines and avoid phantom trailing lines', () => {
  for (const [text, expected] of [
    ['', [0, 0]], ['a', [1, 1]], ['a\n', [1, 1]], ['a\n\n', [2, 1]],
    ['\n', [1, 0]], ['a\r\n\t\r\nb', [3, 2]], ['  \u2003\n', [1, 0]],
    ['// comment\n', [1, 1]], ['a\rb', [1, 1]], ['\ufeff', [1, 0]], ['\ufeff\n', [1, 0]]
  ]) assert.deepEqual(Object.values(lineCounts(text)), expected, JSON.stringify(text));
});

