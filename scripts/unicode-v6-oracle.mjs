import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { strict as assert } from 'node:assert';
import { stripTypeScriptTypes } from 'node:module';
import { runInNewContext } from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { verifyOrGenerate } from './oracle-fixture.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
async function fixture(relative, content) {
  const file = path.join(root, relative);
  await verifyOrGenerate(file, content, process.argv.includes('--generate') || process.argv.includes('--generate-tables'));
}
const sourceRoot = path.join(root, 'source_repo/src/common');
const sources = {};
for (const relative of ['input/UnicodeV6.ts', 'input/UnicodeV6.test.ts', 'services/UnicodeService.ts']) {
  sources[relative] = await readFile(path.join(sourceRoot, relative), 'utf8');
}
function transpile(source) {
  return stripTypeScriptTypes(source.replace(/^import .*;\r?\n/gm, '').replace(/^export /gm, ''));
}
const service = transpile(sources['services/UnicodeService.ts']);
const v6 = transpile(sources['input/UnicodeV6.ts']);
let assertions = 0;
const sandbox = {
  assert: { equal(actual, expected, message) { assertions++; assert.equal(actual, expected, message); } },
  it(name, callback) { callback(); },
};
const provider = runInNewContext(`${service}\n${v6}\n${transpile(sources['input/UnicodeV6.test.ts'])}\nnew UnicodeV6();`, sandbox);
assert.equal(assertions, 65536);
const widths = Buffer.alloc(0x110000);
for (let i = 0; i < widths.length; i++) widths[i] = provider.wcwidth(i);
function runs(buffer) {
  const lines = [];
  let start = 0;
  for (let i = 1; i <= buffer.length; i++) {
    if (i === buffer.length || buffer[i] !== buffer[start]) {
      lines.push(`${start.toString(16)} ${i.toString(16)} ${buffer[start]}`);
      start = i;
    }
  }
  return `${lines.join('\n')}\n`;
}
const fixtures = path.join(root, 'crates/xterm-core/tests/fixtures');
await mkdir(fixtures, { recursive: true });
await fixture('crates/xterm-core/tests/fixtures/unicode_v6_widths.txt', runs(widths));
// Preserve exact raw-provider behavior, including the reserved packed width 3.
const properties = [];
for (const preceding of [0, 1, 2, 3, 4, 5, 6, 7, 8, 0xffffffff, 0x80000000]) {
  for (const codepoint of [0, 31, 32, 127, 0x301, 0x1100, 0x303f, 0x1d167, 0x20000, 0x10ffff]) {
    properties.push(`${codepoint.toString(16)} ${preceding.toString(16)} ${provider.charProperties(codepoint, preceding)}`);
  }
}
await fixture('crates/xterm-core/tests/fixtures/unicode_v6_properties.txt', `${properties.join('\n')}\n`);
if (process.argv.includes('--generate-tables')) {
  let output = '// Copyright (c) 2019 The xterm.js authors. All rights reserved.\n// Licensed under the MIT license. Generated by scripts/unicode-v6-oracle.mjs.\n';
  for (const name of ['BMP_COMBINING', 'HIGH_COMBINING']) {
    const content = sources['input/UnicodeV6.ts'].match(new RegExp(`const ${name} = \\[([\\s\\S]*?)\\];`))[1];
    const ranges = [...content.matchAll(/\[(0x[\da-f]+), (0x[\da-f]+)\]/gi)];
    assert.ok(ranges.length > 0);
    output += `\npub const ${name}: &[(u32, u32)] = &[\n`;
    output += ranges.map(match => `    (${match[1]}, ${match[2]}),`).join('\n');
    output += '\n];\n';
  }
  await writeFile(path.join(root, 'crates/xterm-core/src/unicode_v6_tables.rs'), output);
}
const summary = {
  scope: 'UnicodeV6 only, not terminal equivalence',
  node: process.version,
  platform: process.platform,
  architecture: process.arch,
  upstreamTests: 1,
  upstreamAssertions: assertions,
  differentialCodepoints: widths.length,
  propertyCases: properties.length,
  widthSha256: createHash('sha256').update(widths).digest('hex'),
  sourceHashes: Object.fromEntries(Object.entries(sources).map(([name, content]) => [name, createHash('sha256').update(content).digest('hex')])),
};
await mkdir(path.join(root, 'results/unicode-v6'), { recursive: true });
await writeFile(path.join(root, 'results/unicode-v6/oracle.json'), `${JSON.stringify(summary, null, 2)}\n`);
console.log(JSON.stringify(summary, null, 2));
